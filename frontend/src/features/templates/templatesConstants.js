    blood_group: studentData.blood_group || studentData.bloodGroup || '',
    date_of_birth: studentData.date_of_birth || studentData.dateOfBirth || '',
    dob: studentData.date_of_birth || studentData.dateOfBirth || '',
    gender: studentData.gender || '',
    mobile: studentData.mobile || studentData.emergencyContact || studentData.emergency_contact || '',
    emergency_contact: studentData.emergency_contact || studentData.emergencyContact || '',
